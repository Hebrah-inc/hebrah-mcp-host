#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const sdkRoot = join(root, '..', 'hebrah-sdk-node')

const pkg = JSON.parse(readFileSync(join(sdkRoot, 'package.json'), 'utf8'))
const readme = readFileSync(join(sdkRoot, 'README.md'), 'utf8')

const MCP_TO_SDK = [
  ['get_sandbox_catalog', 'client.sandbox.catalog(connectionId?)'],
  ['list_sandbox_domains', 'client.sandbox.domains()'],
  ['get_sandbox_domain', 'client.sandbox.domain(id)'],
  ['get_synthetic_resource', 'client.sandbox.resource(type, id, patientId?)'],
  ['run_sandbox_scenario', 'client.sandbox.runScenario(scenarioId, params?)'],
  ['get_payer_rules', 'client.sandbox.payerRules(payerId)'],
  ['list_hl7_templates', 'client.sandbox.hl7Templates()'],
  ['inject_hl7', 'client.sandbox.injectHl7(params?)'],
  ['list_webhook_deliveries', 'client.webhooks.listDeliveries(params?)'],
  ['replay_webhook_delivery', 'client.webhooks.replayDelivery(deliveryId)'],
  ['configure_webhook_reliability', 'client.sandbox.configureWebhookReliability(profile)'],
  ['run_webhook_reliability_scenario', 'client.sandbox.runWebhookReliabilityScenario(scenarioId, params?)'],
  ['trigger_test_webhook', 'client.webhooks.triggerMockEvent({ event?, patientId?, connectionId?, scenarioId? })'],
  ['register_smart_client', 'client.smart.registerClient(params)'],
  ['start_smart_launch', 'client.smart.launch(params)'],
  ['run_mpi_match', 'client.sandbox.runMpiMatch(params?)'],
  ['get_practitioner_credentialing', 'client.sandbox.getPractitionerCredentialing(practitionerId)'],
  ['run_aggregator_query', 'client.sandbox.runAggregatorQuery(params)'],
  ['get_synthetic_ehr_profile', 'client.sandbox.getSyntheticEhrProfile(connectionId?)'],
  ['list_ehr_base_models', 'client.sandbox.listEhrModels()'],
  ['reset_synthetic_ehr_data', 'client.sandbox.resetSyntheticEhr(connectionId?)']
]

const mappingTable = [
  '',
  '## MCP tool → SDK method mapping',
  '',
  'Use MCP tools to explore and configure the sandbox. Use `@hebrah/sdk` in your application code:',
  '',
  '| MCP tool | `@hebrah/sdk` |',
  '|----------|---------------|',
  ...MCP_TO_SDK.map(([tool, method]) => `| \`${tool}\` | \`${method}\` |`),
  ''
].join('\n')

const markdown = `${readme}${mappingTable}`

const outDir = join(root, 'src', 'generated')
mkdirSync(outDir, { recursive: true })

const mcpToSdkObject = Object.fromEntries(MCP_TO_SDK)

const out = `// Generated by scripts/sync-sdk-reference.mjs — do not edit manually.
// Re-run: pnpm predev or pnpm prebuild

export const NODE_SDK_PACKAGE = ${JSON.stringify(pkg.name)} as const
export const NODE_SDK_VERSION = ${JSON.stringify(pkg.version)} as const
export const NODE_SDK_NPM_URL = 'https://www.npmjs.com/package/@hebrah/sdk' as const

export const NODE_SDK_REFERENCE_MARKDOWN = ${JSON.stringify(markdown)} as const

export const MCP_TO_SDK: Record<string, string> = ${JSON.stringify(mcpToSdkObject, null, 2)} as const
`

writeFileSync(join(outDir, 'nodeSdkReference.ts'), out, 'utf8')
console.log(`Synced ${pkg.name}@${pkg.version} → src/generated/nodeSdkReference.ts`)
